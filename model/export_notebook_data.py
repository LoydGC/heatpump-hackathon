"""Export what model.ipynb reads, so the dashboard can run the same search in the browser.

Uses model/optimize.py (the notebook as a module) for every step, so the page and the Python run share one definition:
  - the notebook's building table (Minneapolis, Single-Family Detached, dropna on its columns; 173 homes, all with parquet loads)
    with unified R, numeric setpoint, area and fuel, plus the std scales find_closest_row divides by
  - each home's hourly heating load (out.load.heating.energy_delivered..kbtu resampled hourly), packed as uint16 in tens of BTU
  - hourly Minneapolis weather (deg F) and the 21 NEEP profiles (cop_max)
Output: ui/notebook-data.js (window.NB_DATA). Run from the repo root:  python3 model/export_notebook_data.py
"""
import base64
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(__file__))
import optimize as nbm  # noqa: E402


def main():
    df = nbm.load_buildings()
    sp = pd.to_numeric(df["heating_setpoint"].astype("string").str.extract(r"([-+]?\d+(?:\.\d+)?)", expand=False), errors="coerce")
    num = pd.DataFrame({"heating_setpoint": sp, "unified_r_value": pd.to_numeric(df["unified_r_value"]), "area": pd.to_numeric(df["area"])})
    scales = num.std().replace(0, 1)

    temps = nbm.load_weather_f()
    homes = []
    for idx, row in df.iterrows():   # keep the notebook's row order: idxmin takes the first of equal distances
        dem = nbm.load_hourly_demand_btu(row["building_id"])
        n = min(len(temps), len(dem), 8760)
        units = np.rint(dem[:n] / 10.0)
        assert units.max() < 65536, row["building_id"]
        homes.append({"id": row["building_id"], "fuel": row["heating_fuel"], "setpointF": float(sp[idx]),
                      "unifiedR": float(row["unified_r_value"]), "areaSqft": float(row["area"]),
                      "load": base64.b64encode(units.astype("<u2").tobytes()).decode("ascii")})
    n = min(len(temps), 8760)

    profiles = []
    for label, p in nbm.load_neep_machine_profiles(cop_col="cop_max").items():
        ts = sorted(p["capacity_ratings"])
        profiles.append({"id": label, "brand": p["brand"], "outdoorUnit": p["outdoor_unit"], "nominalTons": p["nominal_tons"],
                         "t": ts, "cap": [p["capacity_ratings"][t] for t in ts], "cop": [p["cop_ratings"][t] for t in sorted(p["cop_ratings"])]})
    profiles.sort(key=lambda q: q["nominalTons"])

    out = {"source": "model.ipynb via model/optimize.py; exported by model/export_notebook_data.py", "hours": n,
           "scales": {k: float(v) for k, v in scales.items()}, "notebookHome": "274938",
           "tempF": [round(float(t), 3) for t in temps[:n]], "homes": homes, "profiles": profiles}
    with open("ui/notebook-data.js", "w") as f:
        f.write("// Generated by model/export_notebook_data.py from the data model.ipynb reads. Do not edit by hand.\nwindow.NB_DATA = ")
        json.dump(out, f, separators=(",", ":"))
        f.write(";\n")
    print("homes", len(homes), "profiles", len(profiles), "bytes", os.path.getsize("ui/notebook-data.js"))


if __name__ == "__main__":
    main()
