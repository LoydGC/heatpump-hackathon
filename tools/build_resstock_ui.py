"""Build ui/resstock.js (ResStock dropdown options + per-cell reference figures) from the
city extracts in the project folder datasets/resstock/ (ResStock amy2018 release 1, baseline upgrade 0).
Usage: python3 tools/build_resstock_ui.py /mnt/project-files/datasets/resstock ui/resstock.js
Reference figures are ResStock model-population medians (weighted by `weight`), NOT outputs of our model."""
import sys, json
import pandas as pd, numpy as np

src, out = sys.argv[1], sys.argv[2]
DROPPED = ["0-499","4000+"]  # Gavin 2026-11-08: dropped from consideration
FINE = ["500-749","750-999","1000-1499","1500-1999","2000-2499","2500-2999","3000-3999"]
COARSE = ["0-1499","1500-2499","2500-3999"]  # 0-1499 excludes homes under 500 sq ft
TYPES = {"Single-Family Detached": "sfd", "Single-Family Attached": "sfa"}
CITIES = {"minneapolis": "Minneapolis", "boston": "Boston", "fairbanks": "Fairbanks"}

def wmed(v, w):
    o = np.argsort(v.values); v = v.values[o]; w = w.values[o]; c = np.cumsum(w)
    return float(v[np.searchsorted(c, c[-1] / 2)])

data = {}
for cid in CITIES:
    df = pd.read_csv(f"{src}/{cid}_metadata_upgrade0_all_types.csv")
    df = df[~df["in.geometry_floor_area"].isin(DROPPED)]
    city = {}
    for tname, tid in TYPES.items():
        t = df[df["in.geometry_building_type_recs"] == tname]
        for level, col, bins in (("fine", "in.geometry_floor_area", FINE), ("coarse", "in.geometry_floor_area_bin", COARSE)):
            for b in bins:
                g = t[t[col] == b]; n = len(g)
                cell = {"n": n}
                if n:
                    w = g["weight"]
                    cell.update(sqft=round(float(np.average(g["in.sqft..ft2"], weights=w))),
                                kwh=round(wmed(g["kwh"], w)), therms=round(wmed(g["therms"], w)),
                                otherKwh=round(wmed(g["other_fuel_kwh"], w)))
                city[f"{tid}|{level}|{b}"] = cell
    data[cid] = city

js = ("// GENERATED by tools/build_resstock_ui.py from datasets/resstock (ResStock amy2018 release 1, baseline).\n"
      "// Cells: n = ResStock models, sqft = weighted mean size, kwh/therms/otherKwh = weighted MEDIAN annual use.\n"
      "// These are ResStock reference figures, not outputs of our model.\n"
      "window.RESSTOCK = " + json.dumps({"fine": FINE, "coarse": COARSE, "cities": CITIES, "cells": data}, separators=(",", ":")) + ";\n")
open(out, "w").write(js)
print(out, len(js), "bytes")
